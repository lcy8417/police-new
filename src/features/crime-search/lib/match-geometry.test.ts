import { describe, it, expect } from "vitest"

import { scaleBbox, scalePoint } from "./match-geometry"

describe("scalePoint", () => {
  it("size=[h, w] 순서를 지켜 x는 width, y는 height로 나눈다", () => {
    // size=[400,200] → h=400, w=200. 원점(w, h)=(200, 400)이 표시 우하단(100, 200)에 앉아야.
    expect(scalePoint([400, 200], [100, 200], [200, 400])).toEqual([100, 200])
  })

  it("절반 배율에서 중앙점을 정확히 반으로 줄인다", () => {
    expect(scalePoint([400, 200], [100, 200], [100, 200])).toEqual([50, 100])
  })

  it("query/ref 상이 크기에서 각자 배율로 스케일한다", () => {
    // query 400x200 → 표시 200x100(절반), 같은 원본좌표라도 ref 200x100 → 표시 200x100(등배)
    expect(scalePoint([400, 200], [100, 200], [50, 100])).toEqual([25, 50])
    expect(scalePoint([100, 200], [200, 100], [50, 100])).toEqual([50, 100])
  })

  it("소수 배율(등배가 아닌)에서도 정확하다", () => {
    // size=[300,150] → 표시 [75,150]: sx=0.5, sy=0.5
    expect(scalePoint([300, 150], [75, 150], [50, 100])).toEqual([25, 50])
  })

  it("경계값: 원점(0,0)은 (0,0)", () => {
    expect(scalePoint([400, 200], [100, 200], [0, 0])).toEqual([0, 0])
  })

  it("원본 크기가 0이면 0을 반환해 NaN/Infinity를 막는다", () => {
    expect(scalePoint([0, 0], [100, 100], [5, 5])).toEqual([0, 0])
    expect(scalePoint([0, 200], [100, 100], [50, 5])).toEqual([25, 0])
  })

  it("표시 크기가 원본보다 클 때(확대) 배율이 1을 넘는다", () => {
    expect(scalePoint([100, 100], [200, 200], [50, 50])).toEqual([100, 100])
  })
})

describe("scaleBbox", () => {
  it("위치와 크기를 모두 스케일한다", () => {
    // size=[400,200] → 표시 [100,200]: sx=0.5, sy=0.5
    expect(scaleBbox([400, 200], [100, 200], [20, 40, 100, 200])).toEqual([10, 20, 50, 100])
  })

  it("size=[h, w] 순서로 w는 x축, h는 y축 배율을 쓴다", () => {
    // sx=100/200=0.5, sy=300/600=0.5 이지만 x/y 배율이 다른 케이스로 확인
    // size=[600,200] → 표시 [100,300]: sx=100/200=0.5, sy=300/600=0.5
    expect(scaleBbox([600, 200], [100, 300], [200, 600, 200, 600])).toEqual([100, 300, 100, 300])
  })

  it("비등방(sx≠sy) 배율을 x/y 각각 적용한다", () => {
    // size=[200,100] → 표시 [50,40]: sx=50/100=0.5, sy=40/200=0.2
    expect(scaleBbox([200, 100], [50, 40], [10, 10, 20, 100])).toEqual([5, 2, 10, 20])
  })

  it("경계값: 전체 이미지 박스는 표시 전체를 덮는다", () => {
    expect(scaleBbox([400, 200], [100, 200], [0, 0, 200, 400])).toEqual([0, 0, 100, 200])
  })

  it("원본 크기가 0이면 0을 반환한다", () => {
    expect(scaleBbox([0, 0], [100, 100], [1, 2, 3, 4])).toEqual([0, 0, 0, 0])
  })
})
